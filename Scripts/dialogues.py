def get_tier(score, score_seuil=30, max_tier=9):
    """Retourne le palier (0..max_tier) toutes les score_seuil points.

    Utilisé pour deux progressions distinctes et volontairement découplées :
    - le palier de POSE change tous les 5 points (score_seuil=5, max_tier=59)
      pour exploiter une bien plus grande partie de la banque d'images ;
    - le palier de DIALOGUE change tous les 30 points (score_seuil=30,
      max_tier=9). Chaque palier de dialogue couvre donc exactement 30
      coups (le score augmente de 1 par coup) : les listes "hit" ont 30
      répliques chacune pour qu'aucune ne soit jamais réutilisée avant que
      toutes les autres du palier soient passées (voir ShuffleBag dans
      Scripts/Sprites.py).
    """
    return min(score // score_seuil, max_tier)


POSE_SCORE_SEUIL = 5
POSE_MAX_TIER = 59
DIALOGUE_SCORE_SEUIL = 30
DIALOGUE_MAX_TIER = 9


def get_pose_tier(score):
    return get_tier(score, POSE_SCORE_SEUIL, POSE_MAX_TIER)


def get_dialogue_tier(score):
    return get_tier(score, DIALOGUE_SCORE_SEUIL, DIALOGUE_MAX_TIER)
